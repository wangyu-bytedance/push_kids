"""Generate first-paint tokens from the authoritative JavaScript theme registry."""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    script = (
        "console.log(JSON.stringify("
        "require('./apps/miniprogram/presentation/theme/registry').baseTokens))"
    )
    tokens = json.loads(subprocess.check_output(["node", "-e", script], cwd=ROOT, text=True))
    body = "\n".join(f"  --{key}: {value};" for key, value in tokens.items())
    target = ROOT / "apps/miniprogram/styles/tokens.wxss"
    target.write_text(
        "/* Generated by tools/gen_theme_styles.py; edit theme/registry.js. */\npage {\n"
        + body
        + "\n}\n"
    )
    print(f"TOKENS_WRITTEN {len(tokens)}")


if __name__ == "__main__":
    main()
